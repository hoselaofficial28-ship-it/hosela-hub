-- ============================================================================
-- Migrasi data Hosela Hub LAMA (Google Apps Script + Google Sheets)
-- ke Hosela Hub BARU (Supabase).
--
-- File ini TIDAK mengubah data apa pun saat dijalankan. Isinya hanya ALAT:
--   1) kolom + indeks `legacy_id` untuk tabel yang belum punya,
--   2) tabel log `legacy_import_batches`,
--   3) fungsi `import_legacy_rows()`  -> dipakai skrip importer (idempotent),
--   4) fungsi `hapus_data_uji_hub()`   -> membersihkan data uji (dipanggil manual),
--   5) fungsi `legacy_import_summary()`-> laporan rekonsiliasi jumlah baris,
--   6) fungsi `legacy_missing_payroll()`-> daftar bulan yang payroll-nya perlu disusulkan.
--
-- Semua fungsi hanya boleh dipanggil Owner (hoselaofficial28@gmail.com).
-- Aman dijalankan berulang.
-- ============================================================================

begin;

-- ---------------------------------------------------------------------------
-- 1) Tabel tujuan yang belum punya legacy_id (dipakai sebagai kunci impor)
-- ---------------------------------------------------------------------------
alter table public.rules          add column if not exists legacy_id text;
alter table public.work_schedules add column if not exists legacy_id text;
alter table public.late_reviews   add column if not exists legacy_id text;
alter table public.audit_logs     add column if not exists legacy_id text;

create unique index if not exists rules_legacy_id_key          on public.rules(legacy_id);
create unique index if not exists work_schedules_legacy_id_key on public.work_schedules(legacy_id);
create unique index if not exists late_reviews_legacy_id_key   on public.late_reviews(legacy_id);
create unique index if not exists audit_logs_legacy_id_key     on public.audit_logs(legacy_id);

-- ---------------------------------------------------------------------------
-- 2) Log setiap batch impor (bukti + bisa ditelusuri)
-- ---------------------------------------------------------------------------
create table if not exists public.legacy_import_batches (
  id bigint generated by default as identity primary key,
  tabel text not null,
  kunci text not null default 'legacy_id',
  jumlah integer not null default 0,
  aktor uuid,
  catatan text,
  created_at timestamptz not null default now()
);

alter table public.legacy_import_batches enable row level security;

drop policy if exists legacy_import_batches_owner_read on public.legacy_import_batches;
create policy legacy_import_batches_owner_read on public.legacy_import_batches
  for select to authenticated
  using (lower(coalesce(auth.jwt() ->> 'email', '')) = 'hoselaofficial28@gmail.com');

revoke all on public.legacy_import_batches from public, anon, authenticated;
grant select on public.legacy_import_batches to authenticated;

-- ---------------------------------------------------------------------------
-- 3) import_legacy_rows: upsert satu batch baris JSON ke satu tabel
--    Kunci default `legacy_id` -> menjalankan ulang TIDAK menggandakan data.
-- ---------------------------------------------------------------------------
create or replace function public.import_legacy_rows(
  p_tabel text,
  p_rows jsonb,
  p_kunci text default 'legacy_id'
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_kolom text;
  v_set text;
  v_jumlah integer := 0;
  v_tabel_diizinkan text[] := array[
    'profiles','salary_settings','attendance_events','attendance_details','attendance_weekly',
    'attendance_anomalies','attendance_legacy_raw','warning_history','leave_requests','late_reviews',
    'notifications','payroll_runs','payroll_details','payroll_items','kpi_reports','kpi_templates',
    'jobdesks','rules','holidays','announcements','team_ideas','featured_rewards','work_schedules',
    'audit_logs','app_settings'
  ];
begin
  if auth.uid() is null then
    raise exception 'Harus login' using errcode = '28000';
  end if;
  if v_email <> 'hoselaofficial28@gmail.com' then
    raise exception 'Akses ditolak: hanya Owner yang boleh mengimpor data lama' using errcode = '42501';
  end if;
  if not (p_tabel = any(v_tabel_diizinkan)) then
    raise exception 'Tabel % tidak diizinkan untuk impor', p_tabel using errcode = '22023';
  end if;
  if p_kunci not in ('legacy_id', 'id', 'key') then
    raise exception 'Kunci impor % tidak didukung', p_kunci using errcode = '22023';
  end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' then
    raise exception 'p_rows harus berupa array JSON' using errcode = '22023';
  end if;
  if jsonb_array_length(p_rows) = 0 then
    return jsonb_build_object('success', true, 'tabel', p_tabel, 'jumlah', 0);
  end if;
  if jsonb_array_length(p_rows) > 2000 then
    raise exception 'Maksimal 2000 baris per batch (dikirim % baris)', jsonb_array_length(p_rows) using errcode = '22023';
  end if;

  -- Daftar kolom yang boleh diisi: semua kolom tabel, kecuali `id`
  -- (kecuali untuk profiles yang memakai id dari auth.users), dan kecuali
  -- kolom generated.
  select string_agg(quote_ident(column_name), ', ' order by ordinal_position)
    into v_kolom
    from information_schema.columns
   where table_schema = 'public'
     and table_name = p_tabel
     and column_name <> 'id'
     and is_generated = 'NEVER';

  if p_tabel = 'profiles' then
    v_kolom := 'id, ' || v_kolom;
  end if;

  select string_agg(quote_ident(column_name) || ' = excluded.' || quote_ident(column_name), ', ' order by ordinal_position)
    into v_set
    from information_schema.columns
   where table_schema = 'public'
     and table_name = p_tabel
     and column_name <> 'id'
     and column_name <> p_kunci;

  if v_set is null then
    v_set := quote_ident(p_kunci) || ' = excluded.' || quote_ident(p_kunci);
  end if;

  execute format(
    'insert into public.%1$I (%2$s) select %2$s from jsonb_populate_recordset(null::public.%1$I, $1) on conflict (%3$s) do update set %4$s',
    p_tabel, v_kolom, quote_ident(p_kunci), v_set
  ) using p_rows;

  get diagnostics v_jumlah = row_count;

  insert into public.legacy_import_batches(tabel, kunci, jumlah, aktor, catatan)
  values (p_tabel, p_kunci, v_jumlah, auth.uid(), 'import_legacy_rows');

  return jsonb_build_object('success', true, 'tabel', p_tabel, 'kunci', p_kunci, 'jumlah', v_jumlah);
end;
$$;

comment on function public.import_legacy_rows(text, jsonb, text) is
  'Impor batch data Hosela Hub lama (GAS/Sheets) ke tabel Supabase. Upsert berdasarkan legacy_id -> aman diulang. Hanya Owner.';

revoke execute on function public.import_legacy_rows(text, jsonb, text) from public, anon;
grant execute on function public.import_legacy_rows(text, jsonb, text) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 4) hapus_data_uji_hub: bersihkan data uji sebelum migrasi data asli
--    Tidak menyentuh: akun login, app_settings, dan profil Owner.
--    Profil uji (mis. "adi") hanya dinonaktifkan, tidak dihapus.
-- ---------------------------------------------------------------------------
create or replace function public.hapus_data_uji_hub()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_hapus jsonb := '{}'::jsonb;
  v_n integer;
begin
  if auth.uid() is null then
    raise exception 'Harus login' using errcode = '28000';
  end if;
  if v_email <> 'hoselaofficial28@gmail.com' then
    raise exception 'Akses ditolak: hanya Owner yang boleh membersihkan data uji' using errcode = '42501';
  end if;

  delete from public.attendance_telegram_notifications; get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('attendance_telegram_notifications', v_n);
  delete from public.payroll_items;                     get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('payroll_items', v_n);
  delete from public.payroll_details;                   get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('payroll_details', v_n);
  delete from public.payroll_runs;                      get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('payroll_runs', v_n);
  delete from public.attendance_events;                 get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('attendance_events', v_n);
  delete from public.attendance_details;                get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('attendance_details', v_n);
  delete from public.attendance_weekly;                 get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('attendance_weekly', v_n);
  delete from public.attendance_anomalies;              get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('attendance_anomalies', v_n);
  delete from public.attendance_legacy_raw;             get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('attendance_legacy_raw', v_n);
  delete from public.late_reviews;                      get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('late_reviews', v_n);
  delete from public.leave_requests;                    get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('leave_requests', v_n);
  delete from public.warning_history;                   get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('warning_history', v_n);
  delete from public.sanksi_berulang;                   get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('sanksi_berulang', v_n);
  delete from public.notifications;                     get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('notifications', v_n);
  delete from public.kpi_reports;                       get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('kpi_reports', v_n);
  delete from public.team_ideas;                        get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('team_ideas', v_n);
  delete from public.featured_rewards;                  get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('featured_rewards', v_n);
  delete from public.salary_settings where legacy_id is null; get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('salary_settings', v_n);
  delete from public.jobdesks where legacy_id is null;        get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('jobdesks', v_n);
  delete from public.kpi_templates where legacy_id is null;   get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('kpi_templates', v_n);
  delete from public.rules where legacy_id is null;           get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('rules', v_n);
  delete from public.holidays where legacy_id is null;        get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('holidays', v_n);
  delete from public.announcements where legacy_id is null;   get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('announcements', v_n);
  delete from public.work_schedules where legacy_id is null;  get diagnostics v_n = row_count; v_hapus := v_hapus || jsonb_build_object('work_schedules', v_n);

  -- Profil uji (tanpa legacy_id) dinonaktifkan supaya tidak muncul di papan peringkat.
  update public.profiles set status = 'NONAKTIF', updated_at = now()
   where legacy_id is null and bagian <> 'Owner';
  get diagnostics v_n = row_count;
  v_hapus := v_hapus || jsonb_build_object('profil_uji_dinonaktifkan', v_n);

  insert into public.audit_logs(actor, action, target, catatan)
  values (auth.uid(), 'HAPUS_DATA_UJI', 'semua tabel transaksi',
          'Bersih-bersih sebelum migrasi data lama: ' || v_hapus::text);

  return jsonb_build_object('success', true, 'dihapus', v_hapus);
end;
$$;

comment on function public.hapus_data_uji_hub() is
  'Bersihkan data uji Hosela Hub sebelum impor data lama (Owner saja). Akun login dan app_settings tidak disentuh.';

revoke execute on function public.hapus_data_uji_hub() from public, anon;
grant execute on function public.hapus_data_uji_hub() to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 5) Laporan rekonsiliasi: jumlah baris per tabel tujuan
-- ---------------------------------------------------------------------------
create or replace function public.legacy_import_summary()
returns table(tabel text, jumlah bigint, dengan_legacy bigint)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
begin
  if v_email <> 'hoselaofficial28@gmail.com' then
    raise exception 'Akses ditolak: hanya Owner' using errcode = '42501';
  end if;

  return query execute $q$
    select 'profiles'::text, count(*), count(legacy_id) from public.profiles
    union all select 'salary_settings', count(*), count(legacy_id) from public.salary_settings
    union all select 'attendance_events', count(*), count(legacy_id) from public.attendance_events
    union all select 'attendance_details', count(*), count(legacy_id) from public.attendance_details
    union all select 'attendance_weekly', count(*), count(legacy_id) from public.attendance_weekly
    union all select 'attendance_anomalies', count(*), count(legacy_id) from public.attendance_anomalies
    union all select 'attendance_legacy_raw', count(*), count(legacy_id) from public.attendance_legacy_raw
    union all select 'warning_history', count(*), count(legacy_id) from public.warning_history
    union all select 'leave_requests', count(*), count(legacy_id) from public.leave_requests
    union all select 'late_reviews', count(*), count(legacy_id) from public.late_reviews
    union all select 'notifications', count(*), count(legacy_id) from public.notifications
    union all select 'payroll_runs', count(*), count(legacy_id) from public.payroll_runs
    union all select 'payroll_details', count(*), count(legacy_id) from public.payroll_details
    union all select 'payroll_items', count(*), count(legacy_id) from public.payroll_items
    union all select 'kpi_reports', count(*), count(legacy_id) from public.kpi_reports
    union all select 'kpi_templates', count(*), count(legacy_id) from public.kpi_templates
    union all select 'jobdesks', count(*), count(legacy_id) from public.jobdesks
    union all select 'rules', count(*), count(legacy_id) from public.rules
    union all select 'holidays', count(*), count(legacy_id) from public.holidays
    union all select 'announcements', count(*), count(legacy_id) from public.announcements
    union all select 'audit_logs', count(*), count(legacy_id) from public.audit_logs
    order by 1
  $q$;
end;
$$;

comment on function public.legacy_import_summary() is
  'Jumlah baris per tabel tujuan setelah impor data lama, untuk rekonsiliasi. Owner saja.';

revoke execute on function public.legacy_import_summary() from public, anon;
grant execute on function public.legacy_import_summary() to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 6) Bulan yang sudah punya data absensi tapi belum punya payroll
--    -> dipakai untuk "menyusulkan" payroll susulan dari halaman Payroll.
-- ---------------------------------------------------------------------------
create or replace function public.legacy_missing_payroll()
returns table(bulan text, baris_absensi bigint)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select a.bulan, a.baris
    from (select to_char(d.tanggal, 'YYYY-MM') as bulan, count(*) as baris
            from public.attendance_details d
           group by 1) a
   where lower(coalesce(auth.jwt() ->> 'email', '')) = 'hoselaofficial28@gmail.com'
     and not exists (select 1 from public.payroll_runs r where r.bulan = a.bulan)
   order by a.bulan;
$$;

comment on function public.legacy_missing_payroll() is
  'Bulan yang sudah ada data absensinya tetapi belum ada payroll run — daftar kerja untuk menyusulkan payroll. Owner saja.';

revoke execute on function public.legacy_missing_payroll() from public, anon;
grant execute on function public.legacy_missing_payroll() to authenticated, service_role;

